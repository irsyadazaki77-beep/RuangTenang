import 'dotenv/config';
import { ollamaService } from '../server/services/ai/ollamaService.js';
import { refreshOllamaInventory } from '../server/services/ai/ollamaRuntime.js';
import { smartModelRouter } from '../server/services/ai/smartModelRouter.js';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('output', { recursive: true });
await refreshOllamaInventory(true);
const results: any[] = [];
const model = 'ollama-qwen3-1.7b';
const structured = await ollamaService.generateResponse({requestedModelId:model,prompt:'Kembalikan objek JSON dengan key status bernilai ok.',responseFormat:'json',maxOutputTokens:100},model);
JSON.parse(structured.text); results.push({test:'json',status:'passed',text:structured.text});
const imageModel='ollama-qwen3.5-0.8b';
const vision = await ollamaService.generateResponse({requestedModelId:imageModel,prompt:'Sebutkan warna utama gambar ini dalam satu kata.',maxOutputTokens:100, attachments:[{mimeType:'image/png',base64:'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aOioAAAAASUVORK5CYII='}]},imageModel);
results.push({test:'vision',status:'passed',text:vision.text});
const parallel = await Promise.all(['ollama-gemma3-1b',model].map(async id => ({ model:id,...await ollamaService.generateResponse({requestedModelId:id,prompt:'Balas dengan kata siap.',maxOutputTokens:32},id)})));
results.push({test:'concurrent-requests',status:'passed',responses:parallel});
for(const profileId of ['tenang-middle','tenang-turbo','kerja-fast','kerja-hard'] as const) results.push({test:profileId,decision:smartModelRouter.routeModel({profileId,workspaceMode:profileId.startsWith('kerja')},'Halo')});
await writeFile('output/local-ai-extra-check.json',JSON.stringify(results,null,2));
console.log(JSON.stringify(results));
